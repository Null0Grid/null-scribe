#!/usr/bin/env node
'use strict';

/**
 * Renders the Flatpak, Snap and AUR packaging for a given build, from packaging/.
 *
 *   flatpak-local <tarball> <outdir>
 *       Flatpak manifest that builds from a local .tar.gz (CI builds the .flatpak bundle from it).
 *   flathub <version> <sha256-x64-tar> <sha256-arm64-tar> <outfile>
 *       Flathub manifest: sources are this release's GitHub tarballs (x86_64 + aarch64).
 *   snap <tarball> <version> <outdir>
 *       snapcraft project (snap/snapcraft.yaml + gui files + the unpacked app) for `snapcraft --destructive-mode`.
 *   aur <version> <sha-x64-tar> <sha-arm64-tar> <sha-icon> <sha-license> <outfile>
 *       AUR PKGBUILD (null-scribe-bin) that installs this release's tarball.
 *   aur-local <version> <tarball> <outdir>
 *       Same PKGBUILD but with local sources, for a `makepkg` test before the release exists.
 *
 * The tarball is electron-builder's linux tar.gz: one top folder (null-scribe_<v>_<arch>/) holding the app.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const PKG = path.join(ROOT, 'packaging');
const APP_ID = 'dev.nullgrid.scribe';
const REPO = 'https://github.com/Null0Grid/null-scribe';

const sha256 = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const copy = (from, to) => {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
};
const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};
const tarUrl = (v, arch) => `${REPO}/releases/download/v${v}/null-scribe_${v}_${arch}.tar.gz`;

/* ---------------- Flatpak ---------------- */

const FINISH_ARGS = [
  '--share=ipc',
  '--socket=wayland',
  '--socket=fallback-x11',
  '--device=dri',
  '--socket=pulseaudio', // microphone recording
  '--share=network', // first-run model download, Ollama, Null Drive
  '--talk-name=org.freedesktop.secrets', // Null Drive token in the system keyring
  '--talk-name=org.freedesktop.Notifications',
  '--filesystem=xdg-documents', // Null Notes vaults usually live here
  '--filesystem=xdg-config/dev.nullgrid.notes:ro', // find Null Notes' recent vaults
];

function flatpakManifest(appSources) {
  const lines = [
    `# Generated by scripts/render-packaging.js from packaging/. Edit those, not this file.`,
    `app-id: ${APP_ID}`,
    `runtime: org.freedesktop.Platform`,
    `runtime-version: '24.08'`,
    `sdk: org.freedesktop.Sdk`,
    `base: org.electronjs.Electron2.BaseApp`,
    `base-version: '24.08'`,
    `command: null-scribe`,
    `separate-locales: false`,
    `finish-args:`,
    ...FINISH_ARGS.map((a) => `  - ${a}`),
    `modules:`,
    `  - name: null-scribe`,
    `    buildsystem: simple`,
    `    build-commands:`,
    `      - mkdir -p /app/null-scribe`,
    `      - cp -a app/. /app/null-scribe/`,
    `      - rm -f /app/null-scribe/chrome-sandbox # zypak provides the sandbox`,
    `      - install -Dm755 null-scribe.sh /app/bin/null-scribe`,
    `      - install -Dm644 ${APP_ID}.desktop /app/share/applications/${APP_ID}.desktop`,
    `      - install -Dm644 ${APP_ID}.metainfo.xml /app/share/metainfo/${APP_ID}.metainfo.xml`,
    `      - install -Dm644 ${APP_ID}.png /app/share/icons/hicolor/512x512/apps/${APP_ID}.png`,
    `    sources:`,
    ...appSources,
    `      - type: file`,
    `        path: null-scribe.sh`,
    `      - type: file`,
    `        path: ${APP_ID}.desktop`,
    `      - type: file`,
    `        path: ${APP_ID}.metainfo.xml`,
    `      - type: file`,
    `        path: ${APP_ID}.png`,
  ];
  return lines.join('\n') + '\n';
}

function copyFlatpakFiles(outdir) {
  copy(path.join(PKG, 'flatpak', 'null-scribe.sh'), path.join(outdir, 'null-scribe.sh'));
  for (const f of [`${APP_ID}.desktop`, `${APP_ID}.metainfo.xml`, `${APP_ID}.png`]) copy(path.join(PKG, 'linux', f), path.join(outdir, f));
}

function flatpakLocal(tarball, outdir) {
  fs.mkdirSync(outdir, { recursive: true });
  copy(tarball, path.join(outdir, 'app.tar.gz'));
  copyFlatpakFiles(outdir);
  write(path.join(outdir, `${APP_ID}.yml`), flatpakManifest([`      - type: archive`, `        path: app.tar.gz`, `        dest: app`]));
}

function flathub(version, shaX64, shaArm64, outfile) {
  write(
    outfile,
    flatpakManifest([
      `      - type: archive`,
      `        url: ${tarUrl(version, 'x64')}`,
      `        sha256: ${shaX64}`,
      `        dest: app`,
      `        only-arches: [x86_64]`,
      `      - type: archive`,
      `        url: ${tarUrl(version, 'arm64')}`,
      `        sha256: ${shaArm64}`,
      `        dest: app`,
      `        only-arches: [aarch64]`,
    ])
  );
}

/* ---------------- Snap ---------------- */

function snap(tarball, version, outdir) {
  const appDir = path.join(outdir, 'app', 'null-scribe');
  fs.mkdirSync(appDir, { recursive: true });
  execFileSync('tar', ['-xzf', tarball, '-C', appDir, '--strip-components=1']);
  fs.rmSync(path.join(appDir, 'chrome-sandbox'), { force: true }); // setuid helpers aren't allowed in snaps
  const yaml = fs.readFileSync(path.join(PKG, 'snap', 'snapcraft.yaml'), 'utf8').replace(/@VERSION@/g, version);
  write(path.join(outdir, 'snap', 'snapcraft.yaml'), yaml);
  copy(path.join(PKG, 'linux', `${APP_ID}.png`), path.join(outdir, 'snap', 'gui', 'null-scribe.png'));
  const desktop = fs
    .readFileSync(path.join(PKG, 'linux', `${APP_ID}.desktop`), 'utf8')
    .replace(/^Icon=.*$/m, 'Icon=${SNAP}/meta/gui/null-scribe.png');
  write(path.join(outdir, 'snap', 'gui', 'null-scribe.desktop'), desktop);
}

/* ---------------- AUR ---------------- */

function aurPkgbuild({ version, sources, sums }) {
  return fs
    .readFileSync(path.join(PKG, 'aur', 'PKGBUILD'), 'utf8')
    .replace(/@VERSION@/g, version)
    .replace('@SOURCE@', sources.common)
    .replace('@SOURCE_X64@', sources.x64)
    .replace('@SOURCE_ARM64@', sources.arm64)
    .replace('@SHA_COMMON@', sums.common)
    .replace('@SHA_X64@', sums.x64)
    .replace('@SHA_ARM64@', sums.arm64);
}

function aur(version, shaX64, shaArm64, shaIcon, shaLicense, outfile) {
  const raw = `https://raw.githubusercontent.com/Null0Grid/null-scribe/v\${pkgver}`;
  write(
    outfile,
    aurPkgbuild({
      version,
      sources: {
        common: `"null-scribe.png::${raw}/build/icon.png" "LICENSE::${raw}/LICENSE"`,
        x64: `"null-scribe-\${pkgver}-x86_64.tar.gz::${REPO}/releases/download/v\${pkgver}/null-scribe_\${pkgver}_x64.tar.gz"`,
        arm64: `"null-scribe-\${pkgver}-aarch64.tar.gz::${REPO}/releases/download/v\${pkgver}/null-scribe_\${pkgver}_arm64.tar.gz"`,
      },
      sums: { common: `'${shaIcon}' '${shaLicense}'`, x64: `'${shaX64}'`, arm64: `'${shaArm64}'` },
    })
  );
}

function aurLocal(version, tarball, outdir) {
  fs.mkdirSync(outdir, { recursive: true });
  const isArm = /arm64|aarch64/.test(path.basename(tarball));
  const local = `null-scribe-${version}-${isArm ? 'aarch64' : 'x86_64'}.tar.gz`;
  copy(tarball, path.join(outdir, local));
  copy(path.join(ROOT, 'build', 'icon.png'), path.join(outdir, 'null-scribe.png'));
  copy(path.join(ROOT, 'LICENSE'), path.join(outdir, 'LICENSE'));
  const sum = sha256(tarball);
  write(
    path.join(outdir, 'PKGBUILD'),
    aurPkgbuild({
      version,
      sources: {
        common: '"null-scribe.png" "LICENSE"',
        x64: isArm ? '' : `"${local}"`,
        arm64: isArm ? `"${local}"` : '',
      },
      sums: {
        common: `'${sha256(path.join(ROOT, 'build', 'icon.png'))}' '${sha256(path.join(ROOT, 'LICENSE'))}'`,
        x64: isArm ? '' : `'${sum}'`,
        arm64: isArm ? `'${sum}'` : '',
      },
    })
  );
}

/* ---------------- CLI ---------------- */

const [cmd, ...args] = process.argv.slice(2);
const usage = () => {
  console.error(fs.readFileSync(__filename, 'utf8').split('*/')[0]);
  process.exit(2);
};
const need = (n) => {
  if (args.length < n || args.slice(0, n).some((a) => !a)) usage();
};

switch (cmd) {
  case 'flatpak-local':
    need(2);
    flatpakLocal(args[0], args[1]);
    break;
  case 'flathub':
    need(4);
    flathub(args[0], args[1], args[2], args[3]);
    break;
  case 'snap':
    need(3);
    snap(args[0], args[1], args[2]);
    break;
  case 'aur':
    need(6);
    aur(...args.slice(0, 6));
    break;
  case 'aur-local':
    need(3);
    aurLocal(args[0], args[1], args[2]);
    break;
  default:
    usage();
}
